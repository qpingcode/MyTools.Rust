# Run from PowerShell 7. Downloads only the selected icons from a pinned release.
$ErrorActionPreference = 'Stop'
$version = '1.66.0'
$root = Split-Path $PSScriptRoot -Parent
$directory = Join-Path $root 'ui/assets/icons'
$names = @(Get-Content (Join-Path $directory 'names.txt') | Where-Object { $_.Trim() })
$base = "https://raw.githubusercontent.com/lucide-icons/lucide/$version"
$names | ForEach-Object -Parallel {
    $name = $_
    try {
        Invoke-WebRequest -Uri "$using:base/icons/$name.svg" -OutFile (Join-Path $using:directory "$name.svg")
    } catch {
        throw "Failed to download Lucide icon ${name}: $_"
    }
} -ThrottleLimit 8
Invoke-WebRequest -Uri "$base/LICENSE" -OutFile (Join-Path $directory 'LICENSE')

$lines = @(
    '// Generated by scripts/update-lucide.ps1. Do not edit by hand.'
    'export global BuiltinIcons {'
    '    private property <image> empty;'
    '    public pure function lookup(name: string) -> image {'
)
foreach ($name in $names) {
    $lines += "        if (name == `"builtin:$name`") { return @image-url(`"assets/icons/$name.svg`"); }"
}
$lines += @('        return empty;', '    }', '}')
[System.IO.File]::WriteAllLines((Join-Path $root 'ui/icons.slint'), $lines)
Write-Output "Vendored $($names.Count) Lucide $version icons."
